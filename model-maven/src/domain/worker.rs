use serde::Serialize;
use serde_json::{Map, Value};
use std::path::Path;

/// Stable Rust-side description of a request sent to the isolated Python worker.
/// Optional fields serialize as explicit `null` values to preserve protocol v1 shape.
#[derive(Debug, Serialize)]
pub struct WorkerRequest<'a> {
    pub protocol_version: u32,
    pub operation: &'a str,
    pub project_root: &'a Path,
    pub model: Option<&'a str>,
    pub model_params: &'a Map<String, Value>,
    pub model_injections: &'a Value,
    pub batch: Option<&'a str>,
    pub batch_params: &'a Map<String, Value>,
    pub batch_binding: Option<&'a str>,
    pub training: bool,
    pub seed: Option<u64>,
    pub variant: Option<&'a Value>,
    pub path: Option<&'a str>,
    pub layer_type: Option<&'a str>,
    pub search: Option<&'a str>,
    pub call: &'a str,
    pub contract: Option<&'a std::path::Path>,
    pub if_contract_sha256: Option<&'a str>,
    pub data_fingerprint: Option<&'a str>,
    pub local_probe: bool,
    pub loss: Option<&'a str>,
    pub training_step: Option<&'a str>,
    pub training_loop: Option<&'a str>,
    pub training_mode: Option<&'a str>,
    pub training_params: &'a Map<String, Value>,
    pub apply_supervision: bool,
    pub expected_supervision_revision: Option<&'a str>,
    pub repeat_of: Option<&'a str>,
    pub repeat_overrides: &'a [String],
    pub parent_run_id: Option<&'a str>,
    pub run_name: Option<&'a str>,
    pub request_id: Option<&'a str>,
    pub expected_source_manifest: Option<&'a Value>,
    pub expected_runtime: Option<&'a Value>,
    pub runtime: &'a Value,
    pub steps: Option<u32>,
    pub optimizer: Option<&'a str>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub optimizer_factory: Option<&'a str>,
    #[serde(skip_serializing_if = "Map::is_empty")]
    pub optimizer_params: &'a Map<String, Value>,
    pub lr: Option<f64>,
    pub weight_decay: Option<f64>,
    pub checkpoint_every: Option<u32>,
    pub checkpoint_input: Option<&'a str>,
    pub expected_checkpoint_sha256: Option<&'a str>,
    pub migration_checkpoint_input: Option<&'a str>,
    pub migration_plan: Option<&'a Value>,
    pub allow_state_reset: bool,
    pub checkpoint_dir: Option<&'a Path>,
    pub interactive_progress: bool,
    pub progress_path: Option<&'a Path>,
    pub stop_file: Option<&'a Path>,
    pub edit: Option<&'a Value>,
    pub require_forward: bool,
}
