#!/usr/bin/env python3
"""Single project: build, repair, mark, train, compare, evaluate and export."""
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
import time

root = Path(__file__).resolve().parent.parent
tui = os.environ.get("MODEL_MAVEN_TUI_BIN", str(root / "target/debug/m-model-tui"))
cli = os.environ.get("MODEL_MAVEN_CLI", str(root.parent / "model-maven/target/debug/m-model"))
with tempfile.TemporaryDirectory(prefix="maven-journey-a-") as directory:
    project = Path(directory) / "project"
    project.mkdir()
    destination = Path(directory) / "export"
    env = dict(os.environ, MODEL_MAVEN_TUI_PREFERENCES=str(project / "prefs.json"), COLUMNS="160")
    trace_path = Path(directory) / "tui-cli-receipts.jsonl"
    wrapper = Path(directory) / "trace-cli.py"
    wrapper.write_text(f'''#!/usr/bin/env python3
import json, os, subprocess, sys
result = subprocess.run([{cli!r}] + sys.argv[1:], capture_output=True)
try:
    report = json.loads(result.stdout)
except (ValueError, UnicodeDecodeError):
    report = None
entry = json.dumps({{"args": sys.argv[1:], "returncode": result.returncode, "report": report}}, ensure_ascii=False).encode() + b"\\n"
fd = os.open({str(trace_path)!r}, os.O_CREAT | os.O_WRONLY | os.O_APPEND, 0o600)
os.write(fd, entry)
os.close(fd)
sys.stdout.buffer.write(result.stdout)
sys.stderr.buffer.write(result.stderr)
sys.exit(result.returncode)
''')
    wrapper.chmod(0o755)
    transcripts = []
    receipts = []
    def session(inputs):
        result = subprocess.run([tui, "--line-mode", "--lang", "en", "--cli", str(wrapper)], cwd=project, env=env,
                                input=inputs, capture_output=True, text=True, timeout=240, check=True)
        transcripts.append({"stdin": inputs, "stdout": result.stdout, "stderr": result.stderr})
        return result.stdout
    def run(*args):
        result = subprocess.run([cli, "--json", "--no-interactive", *args], cwd=project, env=env,
                                capture_output=True, text=True, timeout=120)
        report = json.loads(result.stdout)
        assert result.returncode == 0, report
        receipts.append({"args": list(args), "report": report})
        return report
    assert not any(project.iterdir()), "journey must begin in an empty directory"
    created = session("\nm\nimage=3,4,4;tabular=5\n3\ny\nq\n")
    assert "Custom model project created." in created, created
    # These are author-provided component and evaluator implementations, not generated by the tool.
    (project / "components.py").write_text('''import torch
from torch import nn
def broken(): return nn.Linear(2, 2)
def image_encoder(): return nn.ReLU()
def tabular_encoder(): return nn.Identity()
class Fusion(nn.Module):
    def forward(self, values): return torch.cat(values, dim=1)
def fusion(): return Fusion()
def head(): return nn.Linear(53, 3)
''')
    (project / "evaluation.py").write_text('''import model_starter
def data(): return model_starter.batch()
def evaluate(model, data, context):
    output = model(**data["kwargs"])
    context.report_samples(2)
    context.report_prediction("example-0", output[0].tolist())
    return {"metrics": {"mean_abs": float(output.abs().mean())}}
''')
    build = ("\na\n\nimage_encoder\ncomponents:broken\n"
             "a\n\nimage_encoder\ncomponents:image_encoder\ny\n"
             "a\n\ntabular_encoder\ncomponents:tabular_encoder\ny\n"
             "a\n\nfusion\ncomponents:fusion\ny\n"
             "a\n\nhead\ncomponents:head\ny\n"
             "a\nroute\nimage_encoder\ntabular\n"
             "a\nroute\nimage_encoder\nimage\nn\ny\n"
             "a\ngenerate\n\ny\n"
             "2\n\n\n"
             "t\n2\n\nfused\nFinite fused representation\ny\nfinite\nrequire\n\ny\n"
             "r\ntry-wait\n\n\n\n\n\n\ny\ny\nq\n")
    output = session(build)
    assert output.count("FORWARD_FAILED") >= 2, output[-10000:]
    assert "Input route preview" in output, output[-10000:]
    assert "Python model factory: model_starter:model" in output, output[-10000:]
    assert "open the factory's Python module in your editor" in output, output[-10000:]
    assert "(2x10 and 53x3)" in output and "model.head  #1  Linear" in output, output[-10000:]
    calls = [json.loads(line) for line in trace_path.read_text().splitlines()]
    route_attempts = [call for call in calls if "route" in call["args"]]
    failed_route = next(call for call in route_attempts if "tabular" in call["args"])
    assert failed_route["report"]["status"] == "error", failed_route
    assert failed_route["report"]["data"]["failure_location"]["last_observed_module_call"]["paths"] == ["model.head"], failed_route
    assert any("image" in call["args"] and call["report"]["status"] == "success"
               and call["report"]["data"]["committed"] is True for call in route_attempts), route_attempts
    assert output.count("Assembly saved") >= 4 and "Generate assembly adapter" in output, output[-10000:]
    assert "Mark saved:" in output and "Rule preview" in output, output[-10000:]
    assert "Specifying an axis requires stable sample IDs" in output, output[-10000:]
    assert "Run started or completed" in output, output[-10000:]
    state = json.loads((project / ".model-maven/semantic-marks.json").read_text())
    assert state["marks"][0]["module_path"] == "model.fusion", state
    assert state["marks"][0]["rules"][0]["kind"] == "finite", state
    assert state["marks"][0]["rules"][0]["mode"] == "require", state
    assert (project / "generated/model_assembly.py").is_file()
    config = json.loads((project / ".model-maven/project.json").read_text())
    assert config["model_params"]["input_routes"]["image_encoder"] == "image", config
    ids = []
    for _ in range(2):
        launched = session("\nr\ntrain\n\n\n\n1\n\ny\ny\nq\n")
        match = re.search(r"Run ID:\s*(\S+)", launched)
        assert match, launched
        run_id = match.group(1)
        ids.append(run_id)
        deadline = time.monotonic() + 60
        while time.monotonic() < deadline:
            detail = run("runs", "attach", run_id, "--follow=false")
            status = detail["data"]["record"]["status"]
            if status not in ("running", "stopping"): break
            time.sleep(0.25)
        assert status == "completed", detail
        saved = run("runs", "show", run_id)["data"]
        assert saved["inputs"]["apply_supervision"] is True, saved
        rules = saved["report"]["data"]["supervision"]["rules"]
        assert any(rule["kind"] == "finite" and rule["mode"] == "require"
                   and rule["steps_observed"] == 1 and rule["element_count"] > 0 for rule in rules), rules
    assert ids[0] != ids[1]
    listing = run("runs", "list")["data"]["runs"]
    chosen = next(i for i, item in enumerate(listing, 1) if item["id"] == ids[1])
    other = next(i for i, item in enumerate(listing, 1) if item["id"] == ids[0])
    outcome = session(f"\nj\n{chosen}\ncompare\n{other}\n"
                      "evaluate\nevaluation:evaluate\nevaluation:data\ntest\n\n\n\n\n\ny\n"
                      f"export\n{destination}\ny\nb\nb\nq\n")
    assert "Run comparison" in outcome and "data: unknown" in outcome and "samples: unknown" in outcome, outcome[-10000:]
    assert "Supervision measurements" in outcome and "measured steps: 1" in outcome and "elements: 106" in outcome, outcome[-10000:]
    assert "Sample localization is insufficient" in outcome, outcome[-10000:]
    assert "Evaluation result" in outcome and "example-0" in outcome, outcome[-10000:]
    assert "Export completed" in outcome and (destination / "manifest.json").is_file(), outcome[-10000:]
    restore_env = env.copy(); restore_env.pop("PYTHONPATH", None); restore_env.pop("PYTHONHOME", None)
    hidden = project.with_name("hidden-project")
    project.rename(hidden)
    try:
        restored = subprocess.run([sys.executable, "restore_model.py"], cwd=destination, env=restore_env,
                                  capture_output=True, text=True, timeout=120)
    finally:
        hidden.rename(project)
    assert restored.returncode == 0, (restored.stdout, restored.stderr)
    evidence_path = os.environ.get("MODEL_MAVEN_JOURNEY_EVIDENCE")
    if evidence_path:
        evidence = Path(evidence_path).resolve()
        evidence.mkdir(parents=True, exist_ok=False)
        (evidence / "tui-sessions.json").write_text(json.dumps(transcripts, ensure_ascii=False, indent=2) + "\n")
        (evidence / "cli-receipts.json").write_text(json.dumps(receipts, ensure_ascii=False, indent=2) + "\n")
        shutil.copy2(trace_path, evidence / "tui-cli-receipts.jsonl")
        shutil.copy2(wrapper, evidence / "trace-cli.py")
        for name in ("model_starter.py", "components.py", "evaluation.py"):
            shutil.copy2(project / name, evidence / name)
        shutil.copy2(project / ".model-maven/semantic-marks.json", evidence / "semantic-marks.json")
        shutil.copytree(destination, evidence / "export")
        print(f"Evidence preserved: {evidence}")
    print("Journey A: TUI builds, repairs, marks, constrains, trains twice, compares, evaluates and exports; isolated weights restore")
